    def save_report(self, case_data: Dict, format: str = "html") -> str:
        """Save report to file"""
        timestamp = datetime.utcnow().strftime("%Y%m%d_%H%M%S")
        case_id = case_data.get("id", "case").replace(" ", "_")
        
        if format == "html":
            content = self.generate_html_report(case_data)
            filename = f"{case_id}_report_{timestamp}.html"
        elif format == "json":
            content = json.dumps(case_data, indent=2)
            filename = f"{case_id}_data_{timestamp}.json"
        elif format == "stix":
            content = json.dumps(self.generate_stix_export(case_data), indent=2)
            filename = f"{case_id}_stix_{timestamp}.json"
        else:
            raise ValueError(f"Unsupported format: {format}")
        
        filepath = os.path.join(self.templates_path, filename)
        with open(filepath, "w") as f:
            f.write(content)
        
        return filepath

