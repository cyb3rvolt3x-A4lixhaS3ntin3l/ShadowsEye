"""
SENTINEL CORE - AUTOMATED REPORT GENERATOR (MALTEGO-STYLE)
Generates comprehensive, classified-grade reports in multiple formats (PDF, HTML, STIX, JSON).
Includes executive summaries, technical annexes, and visual graph exports.
"""
import json
import os
from datetime import datetime
from typing import Dict, List, Any
from collections import defaultdict

class ReportGenerator:
    def __init__(self):
        self.templates_path = "templates"
        os.makedirs(self.templates_path, exist_ok=True)

    def generate_executive_summary(self, case_data: Dict) -> str:
        """Generate high-level executive summary for leadership"""
        entities = case_data.get("entities", [])
        relationships = case_data.get("relationships", [])
        vulnerabilities = [e for e in entities if e.get("type") == "VULNERABILITY"]
        
        # Calculate risk score
        critical_vulns = len([v for v in vulnerabilities if v.get("meta", {}).get("severity") == "critical"])
        high_vulns = len([v for v in vulnerabilities if v.get("meta", {}).get("severity") == "high"])
        risk_score = min(100, (critical_vulns * 25) + (high_vulns * 10) + (len(entities) // 10))
        
        risk_level = "CRITICAL" if risk_score > 75 else "HIGH" if risk_score > 50 else "MEDIUM" if risk_score > 25 else "LOW"
        
        summary = f"""
# EXECUTIVE SUMMARY
**Case ID:** {case_data.get('id', 'N/A')}
**Target:** {case_data.get('target', 'N/A')}
**Generated:** {datetime.utcnow().isoformat()}
**Classification:** INTERNAL USE ONLY

## RISK ASSESSMENT
- **Overall Risk Score:** {risk_score}/100
- **Risk Level:** {risk_level}
- **Critical Vulnerabilities:** {critical_vulns}
- **High Severity Vulnerabilities:** {high_vulns}

## KEY FINDINGS
- Total Entities Discovered: {len(entities)}
- Infrastructure Relationships Mapped: {len(relationships)}
- Attack Surface Coverage: {'COMPREHENSIVE' if len(entities) > 50 else 'PARTIAL'}

## IMMEDIATE ACTIONS REQUIRED
{self._generate_recommendations(critical_vulns, high_vulns, entities)}

## INTELLIGENCE CONFIDENCE
- Data Sources: {len(set(e.get('source') for e in entities))}
- Average Confidence Score: {sum(e.get('confidence', 0) for e in entities) // max(len(entities), 1)}%

---
*This report was automatically generated by Sentinel Core Intelligence Platform*
"""
        return summary

    def _generate_recommendations(self, critical: int, high: int, entities: List) -> str:
        recs = []
        if critical > 0:
            recs.append("1. **IMMEDIATE**: Patch or mitigate {0} critical vulnerabilities within 24 hours".format(critical))
        if high > 0:
            recs.append("2. **URGENT**: Schedule remediation for {0} high-severity issues within 7 days".format(high))
        
        # Check for exposed services
        ips = [e for e in entities if e.get("type") == "IP"]
        if len(ips) > 5:
            recs.append("3. **REVIEW**: Large IP footprint detected ({0} IPs). Verify necessity of exposed assets.".format(len(ips)))
        
        # Check for subdomains
        domains = [e for e in entities if e.get("type") == "DOMAIN"]
        if len(domains) > 20:
            recs.append("4. **AUDIT**: Extensive subdomain presence ({0} domains). Review for shadow IT or forgotten assets.".format(len(domains)))
        
        if not recs:
            recs.append("1. Continue monitoring. No immediate critical actions identified.")
        
        return "\n".join(recs)

    def generate_technical_annex(self, case_data: Dict) -> str:
        """Generate detailed technical findings for engineers"""
        entities = case_data.get("entities", [])
        
        # Group by type
        by_type = defaultdict(list)
        for entity in entities:
            by_type[entity.get("type", "UNKNOWN")].append(entity)
        
        annex = f"""
# TECHNICAL ANNEX
**Case:** {case_data.get('id', 'N/A')}
**Generated:** {datetime.utcnow().isoformat()}

## ENTITY INVENTORY

"""
        for etype, items in sorted(by_type.items()):
            annex += f"### {etype} ({len(items)} found)\n\n"
            annex += "| Value | Confidence | Source | Metadata |\n"
            annex += "|-------|------------|--------|----------|\n"
            for item in items[:50]:  # Limit to top 50 per type
                meta_str = json.dumps(item.get("meta", {}))[:50] + "..." if len(json.dumps(item.get("meta", {}))) > 50 else json.dumps(item.get("meta", {}))
                annex += f"| {item.get('value', 'N/A')} | {item.get('confidence', 0)}% | {item.get('source', 'N/A')} | {meta_str} |\n"
            
            if len(items) > 50:
                annex += f"\n*...and {len(items) - 50} more {etype} entities omitted for brevity...*\n"
            
            annex += "\n\n"
        
        # Add relationship table
        relationships = case_data.get("relationships", [])
        if relationships:
            annex += "## RELATIONSHIP MAP\n\n"
            annex += "| Source | Type | Target | Confidence |\n"
            annex += "|--------|------|--------|------------|\n"
            for rel in relationships[:100]:
                annex += f"| {rel.get('source', 'N/A')} | {rel.get('type', 'RELATED')} | {rel.get('target', 'N/A')} | {rel.get('confidence', 0)}% |\n"
        
        return annex

    def generate_stix_export(self, case_data: Dict) -> Dict:
        """Export to STIX 2.1 format for threat intelligence sharing"""
        from uuid import uuid4
        
        stix_bundle = {
            "type": "bundle",
            "id": f"bundle--{uuid4()}",
            "objects": []
        }
        
        # Create identity (organization)
        org_identity = {
            "type": "identity",
            "id": f"identity--{uuid4()}",
            "created": datetime.utcnow().isoformat(),
            "modified": datetime.utcnow().isoformat(),
            "name": "Sentinel Core Analysis",
            "identity_class": "system"
        }
        stix_bundle["objects"].append(org_identity)
        
        # Convert entities to STIX observables/indicators
        entities = case_data.get("entities", [])
        for entity in entities:
            etype = entity.get("type", "").upper()
            value = entity.get("value", "")
            
            stix_obj = None
            
            if etype == "IP":
                stix_obj = {
                    "type": "ipv4-addr",
                    "id": f"ipv4-addr--{uuid4()}",
                    "value": value
                }
            elif etype == "DOMAIN":
                stix_obj = {
                    "type": "domain-name",
                    "id": f"domain-name--{uuid4()}",
                    "value": value
                }
            elif etype == "EMAIL":
                stix_obj = {
                    "type": "email-addr",
                    "id": f"email-addr--{uuid4()}",
                    "value": value
                }
            elif etype == "VULNERABILITY":
                cve_id = value if value.startswith("CVE-") else f"CVE-{value}"
                stix_obj = {
                    "type": "vulnerability",
                    "id": f"vulnerability--{uuid4()}",
                    "name": cve_id,
                    "description": entity.get("meta", {}).get("severity", "Unknown severity")
                }
            elif etype == "URL":
                stix_obj = {
                    "type": "url",
                    "id": f"url--{uuid4()}",
                    "value": value
                }
            
            if stix_obj:
                # Add confidence if available
                if entity.get("confidence"):
                    stix_obj["confidence"] = entity.get("confidence")
                
                # Add labels
                stix_obj["labels"] = [f"source:{entity.get('source', 'unknown')}"]
                
                stix_bundle["objects"].append(stix_obj)
        
        return stix_bundle

